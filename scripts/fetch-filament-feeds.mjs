#!/usr/bin/env node
/**
 * Fetch exactly three public Czech Heureka feeds and map them with the
 * existing filament importer. Does not crawl shops, carts, or product pages.
 *
 *   npm run fetch:filament
 *   npm run fetch:filament -- --offline
 *   npm run fetch:filament -- --write-preview src/data/filament-preview.generated.json
 *   npm run fetch:filament -- --refresh --write src/data/offers.generated.ts
 *
 * --offline maps the committed excerpts in scripts/fixtures/snapshots/ and
 * does not use the network. Live output is cached under .cache/filament-feeds/.
 * --write-preview regenerates the local dev catalog. It must not be copied
 * into src/data/offers.ts. Production /srovnavac/ stays noindex.
 */

import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { generatedModule, mapXmlFeed, pricePerKg, provePublicSnapshots } from './import-filament-feed.mjs';
import { BOT_UA, CACHE_MAX_AGE_MS, PUBLIC_SHOPS, REQUEST_GAP_MS, SKIPPED_SHOPS } from './filament-shops.mjs';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const CACHE_DIR = path.join(ROOT, '.cache/filament-feeds');
const DEFAULT_PREVIEW = path.join(ROOT, 'src/data/filament-preview.generated.json');
const MAX_BYTES = 40_000_000;
const PREVIEW_FIELDS = [
  'productId',
  'productName',
  'shopId',
  'shopName',
  'country',
  'currency',
  'price',
  'shippingPrice',
  'inStock',
  'stockLabel',
  'url',
  'imageUrl',
  'fetchedAt',
  'source',
  'category',
  'weightGrams',
  'weightConfidence',
  'material',
  'brand',
  'color',
  'diameterMm',
  'packaging',
];

function parseArgs(argv) {
  const args = {};
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (!token.startsWith('--')) throw new Error(`Unexpected argument ${token}. This command takes no shop URLs.`);
    const key = token.slice(2);
    const next = argv[index + 1];
    if (next === undefined || next.startsWith('--')) {
      args[key] = true;
    } else {
      args[key] = next;
      index += 1;
    }
  }
  return args;
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function assertLocalWrite(target) {
  if (/^[a-z][a-z0-9+.-]*:\/\//i.test(target)) throw new Error(`Refusing remote write target ${target}`);
  const output = path.resolve(target);
  const production = path.join(ROOT, 'src/data/offers.ts');
  if (output === production) {
    throw new Error('Refusing to write src/data/offers.ts. Production /srovnavac/ stays gated.');
  }
  return output;
}

function compactPreviewOffer(offer) {
  const compact = {};
  for (const key of PREVIEW_FIELDS) {
    if (offer[key] !== undefined) compact[key] = offer[key];
  }
  return compact;
}

function previewDocument(offers) {
  const sorted = [...offers].sort((a, b) => {
    const diff = pricePerKg(a) - pricePerKg(b);
    if (diff !== 0) return diff;
    return a.shopName.localeCompare(b.shopName, 'cs') || a.productId.localeCompare(b.productId);
  });
  const byShop = {};
  for (const offer of sorted) byShop[offer.shopId] = (byShop[offer.shopId] ?? 0) + 1;
  return {
    _generated: true,
    _comment:
      'GENERATED by npm run fetch:filament -- --write-preview src/data/filament-preview.generated.json. Accepted rows from the three public Heureka feeds for the local /srovnavac/?preview=1 view only. Do not copy into src/data/offers.ts. Production stays noindex.',
    shops: PUBLIC_SHOPS.map((shop) => ({
      shopId: shop.shopId,
      shopName: shop.shopName,
      kind: shop.kind,
      url: shop.url,
      accepted: byShop[shop.shopId] ?? 0,
    })),
    offers: sorted.map(compactPreviewOffer),
  };
}

async function writePreview(offers, target) {
  const output = assertLocalWrite(target);
  const document = previewDocument(offers);
  await writeFile(output, `${JSON.stringify(document, null, 2)}\n`, 'utf8');
  const cheapest = document.offers[0];
  console.log(
    `Wrote ${document.offers.length} preview rows to ${path.relative(ROOT, output)}. Cheapest: ${cheapest.shopName} ${cheapest.weightGrams}g ${pricePerKg(cheapest)} ${cheapest.currency}/kg.`,
  );
  console.log('This file is the local preview catalog. It is not src/data/offers.ts.');
}

function summarize(shop, result) {
  const reasons = new Map();
  for (const row of result.rejected) reasons.set(row.reason, (reasons.get(row.reason) ?? 0) + 1);
  const reasonText = [...reasons.entries()].map(([reason, count]) => `${reason}=${count}`).join(', ') || 'none';
  console.log(`${shop.shopName}: accepted ${result.accepted.length}, rejected ${result.rejected.length} (${reasonText})`);
  for (const offer of result.accepted.slice(0, 3)) {
    console.log(
      `  ${offer.productId} ${offer.weightGrams}g ${pricePerKg(offer)} ${offer.currency}/kg confidence=${offer.weightConfidence} shipping=${offer.shippingPrice ?? 'unknown'}`,
    );
  }
  const shops = new Set(result.accepted.map((offer) => offer.shopId));
  if (shops.size !== 1) throw new Error(`${shop.shopId}: mapped rows did not stay in one shop`);
}

async function readFreshCache(shop) {
  const xmlPath = path.join(CACHE_DIR, `${shop.shopId}.xml`);
  const metaPath = path.join(CACHE_DIR, `${shop.shopId}.json`);
  const info = await stat(xmlPath);
  const age = Date.now() - info.mtimeMs;
  if (age > CACHE_MAX_AGE_MS) return null;
  const meta = JSON.parse(await readFile(metaPath, 'utf8'));
  if (meta.url !== shop.url) return null;
  return { xml: await readFile(xmlPath, 'utf8'), fetchedAt: meta.fetchedAt, fromCache: true };
}

async function downloadShop(shop) {
  const response = await fetch(shop.url, {
    redirect: 'follow',
    signal: AbortSignal.timeout(60_000),
    headers: {
      'user-agent': BOT_UA,
      accept: 'application/xml, text/xml;q=0.9',
    },
  });
  if (!response.ok) {
    throw new Error(`${shop.shopName}: HTTP ${response.status} for ${shop.url}. Stopped.`);
  }
  const finalHost = new URL(response.url).hostname;
  const expectedHost = new URL(shop.url).hostname;
  if (finalHost !== expectedHost) {
    throw new Error(`${shop.shopName}: redirected to ${finalHost}. Stopped.`);
  }
  const xml = await response.text();
  if (xml.length > MAX_BYTES) throw new Error(`${shop.shopName}: response is over 40 MB. Stopped.`);
  if (!xml.includes('<SHOPITEM')) throw new Error(`${shop.shopName}: response has no SHOPITEM. Stopped.`);
  const fetchedAt = new Date().toISOString();
  await mkdir(CACHE_DIR, { recursive: true });
  await writeFile(path.join(CACHE_DIR, `${shop.shopId}.xml`), xml, 'utf8');
  await writeFile(
    path.join(CACHE_DIR, `${shop.shopId}.json`),
    JSON.stringify({ url: shop.url, fetchedAt, bytes: xml.length, kind: shop.kind }, null, 2),
    'utf8',
  );
  return { xml, fetchedAt, fromCache: false };
}

async function loadShop(shop, refresh) {
  if (!refresh) {
    try {
      const cached = await readFreshCache(shop);
      if (cached) {
        console.log(`${shop.shopName}: using cache from ${cached.fetchedAt}`);
        return cached;
      }
    } catch {
      // Cache miss is normal. A failed download below stops the run.
    }
  }
  console.log(`${shop.shopName}: fetching ${shop.url}`);
  return downloadShop(shop);
}

async function runLive(args) {
  const accepted = [];
  for (let index = 0; index < PUBLIC_SHOPS.length; index += 1) {
    if (index > 0) await sleep(REQUEST_GAP_MS);
    const shop = PUBLIC_SHOPS[index];
    const loaded = await loadShop(shop, Boolean(args.refresh));
    const result = mapXmlFeed(loaded.xml, {
      shopId: shop.shopId,
      shopName: shop.shopName,
      country: shop.country,
      currency: 'CZK',
      source: shop.source,
      fetchedAt: loaded.fetchedAt,
    });
    summarize(shop, result);
    accepted.push(...result.accepted);
  }
  const shopCount = new Set(accepted.map((offer) => offer.shopId)).size;
  console.log(`Mapped ${accepted.length} filament rows from ${shopCount} public XML feeds.`);
  console.log('Production src/data/offers.ts was not modified. /srovnavac/ stays noindex until reviewed rows are merged by hand.');
  if (args.write) {
    const output = assertLocalWrite(String(args.write));
    await writeFile(
      output,
      generatedModule(accepted, {
        fixture: false,
        input: 'allowlisted public Heureka XML',
        note: 'Live fetch. Review weightConfidence and shipping warnings before any merge. Do not import this module from pages.',
      }),
      'utf8',
    );
    console.log(`Wrote ${accepted.length} rows to ${output}.`);
  }
  if (args['write-preview']) {
    const target = args['write-preview'] === true ? DEFAULT_PREVIEW : String(args['write-preview']);
    await writePreview(accepted, target);
  }
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  console.log('Skipped shops:');
  for (const skipped of SKIPPED_SHOPS) console.log(`- ${skipped.shop}: ${skipped.reason}`);
  if (args.offline && args['write-preview']) {
    throw new Error('--offline only checks the small excerpts. It must not overwrite the preview catalog.');
  }
  if (args.offline) {
    const accepted = await provePublicSnapshots();
    console.log(`Offline snapshot proof: ${accepted.length} rows, ${new Set(accepted.map((offer) => offer.shopId)).size} shops.`);
    return;
  }
  await runLive(args);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
